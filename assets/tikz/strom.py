GAP_SPEED = 45  # pt/s for den største strømmen i figuren


def tikz(paths):
    out = ['% strøm:start (generert av strom.py, ikke rediger)']
    for key, lines in paths.items():
        for pts in lines:
            out.append(r'\draw[strom, %s] ' % key + ' -- '.join('(%g,%g)' % p for p in pts) + ';')
    out.append('% strøm:slutt')
    return '\n'.join(out)


def fmt(v):
    a = abs(v)
    s = '%.3g' % a
    if 'e' in s:
        s = '%.4f' % a
    return s


def caption(unit, names, cur, label):
    parts = []
    for k, name in names.items():
        if k in cur and cur[k]:
            parts.append('%s %s %s%s' % (name, fmt(cur[k]), unit, '' if cur[k] > 0 else ' (motsatt vei)'))
        elif k in cur:
            parts.append('%s 0' % name)
    head = (label + ': ') if label else ''
    return head + ', '.join(parts) + '. Farten er proporsjonal med strømmen.'


def wrapper(name, unit, names, modes):
    top = max(abs(v) for _, _, c in modes for v in c.values())
    data = {m: {'view': 'a', 'i': c, 'tekst': caption(unit, names, c, lab)} for m, lab, c in modes}
    btns = ''.join('<button type="button" data-mode="%s">%s</button>' % (m, html.escape(lab))
                   for m, lab, _ in modes) if len(modes) > 1 else ''
    return ('<div class="stromfig" data-fig="%s" data-hidden data-scale="%.4g" data-modes=\'%s\'>'
            '<div class="stromfig__view" data-view="a">' % (name, GAP_SPEED / top, html.escape(json.dumps(data, ensure_ascii=False), quote=False).replace("'", '&#39;')),
            '</div><div class="stromfig__bar">%s<button type="button" class="stromfig__toggle" aria-pressed="false">Vis strøm</button></div>'
            '<p class="stromfig__cap"></p></div>' % btns)


changed = []
for name, (unit, paths, names, modes) in F.items():
    p = os.path.join(HERE, name + '.tex')
    t = open(p, encoding='utf-8').read()
    t2 = re.sub(r'\n% strøm:start.*?% strøm:slutt', '', t, flags=re.S)
    t2 = t2.replace('\\end{circuitikz}', tikz(paths) + '\n\\end{circuitikz}', 1)
    if t2 != t:
        open(p, 'w', encoding='utf-8', newline='\n').write(t2)
        changed.append(name + '.tex')

    pre, post = wrapper(name, unit, names, modes)
    pat = re.compile(r'(?:<div class="stromfig" data-fig="%s"[^>]*><div class="stromfig__view" data-view="a">)?'
                     r'(<!-- tikz:%s -->.*?<!-- /tikz:%s -->)'
                     r'(?:</div><div class="stromfig__bar">.*?</div><p class="stromfig__cap"></p></div>)?'
                     % (re.escape(name), re.escape(name), re.escape(name)), re.S)
    for page in glob.glob(os.path.join(SITE, 'subjects', '**', '*.html'), recursive=True):
        if page.endswith('strom.html'):
            continue
        h = open(page, encoding='utf-8').read()
        h2 = pat.sub(lambda m: pre + m.group(1) + post, h)
        if h2 != h:
            open(page, 'w', encoding='utf-8', newline='\n').write(h2)

